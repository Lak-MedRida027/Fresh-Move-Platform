// @ts-check
import { defineConfig } from 'astro/config';
import cloudflare from '@astrojs/cloudflare';
import { cacheCloudflare } from '@astrojs/cloudflare/cache';

// Public URL used for canonical links, hreflang, sitemap, robots.txt and social cards.
// Set SITE_URL for production builds (e.g. https://fresh-move.<account>.workers.dev or a
// custom domain). See docs/CUSTOM_DOMAIN.md.
const SITE = process.env.SITE_URL ?? 'http://localhost:4321';

export default defineConfig({
  site: SITE,
  // Pages that show trip data render on the server (Cloudflare Worker) with a
  // short edge cache; pages without data opt into prerendering.
  output: 'server',
  adapter: cloudflare({
    // Trip photos are pre-sized at upload (docs/IMAGES.md) and the few local
    // brand images are pre-generated by scripts, so no runtime image service.
    imageService: 'passthrough',
  }),
  // We don't use Astro sessions (admin auth uses Supabase cookies), so no KV namespace.
  session: false,
  // Route caching on Cloudflare's Worker cache; trip pages are tagged "trips" and
  // purged when an admin changes a trip.
  cache: { provider: cacheCloudflare() },
  trailingSlash: 'ignore',
  build: {
    format: 'directory',
    // Keep CSS in external files so the CSP can use style-src 'self' without 'unsafe-inline'.
    inlineStylesheets: 'never',
  },
  security: {
    // Rejects cross-site form posts to on-demand routes (CSRF protection for admin forms).
    checkOrigin: true,
  },
  vite: {
    build: {
      // Astro inlines small bundled scripts below this limit. 0 keeps every
      // script external so the CSP only has to allow the theme bootstrap hash.
      assetsInlineLimit: 0,
      // One stylesheet for the whole site instead of several render-blocking files per page.
      cssCodeSplit: false,
      // The spreadsheet library (admin Excel export, ~930 KB, ~250 KB gzipped) is one
      // chunk loaded only when someone clicks Export. Everything else is far smaller.
      chunkSizeWarningLimit: 1000,
    },
  },
  i18n: {
    locales: ['ar', 'en'],
    defaultLocale: 'ar',
    routing: { prefixDefaultLocale: false },
  },
});

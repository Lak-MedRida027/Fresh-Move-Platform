// Writes public/_headers (security headers for static files on Cloudflare) from
// src/lib/security-headers.ts. Runs before every build (npm run build).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { securityHeaders } from '../src/lib/security-headers.ts';

const themeSrc = readFileSync('src/scripts/theme-init.ts', 'utf8');
const script = themeSrc.match(/THEME_INIT_SCRIPT =\s*"([^"]*)"/)?.[1];
if (!script) throw new Error('THEME_INIT_SCRIPT not found');
const themeScriptHash = createHash('sha256').update(script).digest('base64');

const supabaseUrl = process.env.PUBLIC_SUPABASE_URL ?? readEnvFile('PUBLIC_SUPABASE_URL');
if (!supabaseUrl) throw new Error('PUBLIC_SUPABASE_URL is not set (.env)');

function readEnvFile(name: string): string | undefined {
  try {
    const line = readFileSync('.env', 'utf8').split(/\r?\n/).find((l) => l.startsWith(`${name}=`));
    return line?.slice(name.length + 1).trim() || undefined;
  } catch {
    return undefined;
  }
}

const headers = securityHeaders({ themeScriptHash, supabaseUrl });
const lines = ['# Generated by scripts/write-headers.ts. Do not edit by hand.', '/*'];
for (const [k, v] of Object.entries(headers)) lines.push(`  ${k}: ${v}`);
lines.push('', '/_astro/*', '  Cache-Control: public, max-age=31536000, immutable');
lines.push('', '/hero/*', '  Cache-Control: public, max-age=604800', '', '/brand/*', '  Cache-Control: public, max-age=604800');
lines.push('', '/og/*', '  Cache-Control: public, max-age=604800', '');
writeFileSync('public/_headers', lines.join('\n'));
console.log(`public/_headers written (theme hash ${themeScriptHash.slice(0, 8)}…, Supabase ${new URL(supabaseUrl).host})`);

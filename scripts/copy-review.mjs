// Regenerates docs/COPY_REVIEW.md: every Darja string on the site in one place,
// next to its English counterpart, so the owner can review the copy.
//   node scripts/copy-review.mjs
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { parse } from 'yaml';

const ar = JSON.parse(await readFile('src/i18n/ar.json', 'utf8'));
const en = JSON.parse(await readFile('src/i18n/en.json', 'utf8'));
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

const groups = {};
for (const key of Object.keys(ar)) {
  const group = key.split('.')[0];
  (groups[group] ??= []).push(key);
}

const titles = {
  site: 'Tagline', meta: 'Page titles and descriptions (search results, link previews)', a11y: 'Screen-reader labels',
  nav: 'Navigation', theme: 'Theme toggle', lang: 'Language switch', hero: 'Home: hero', about: 'Home: who we are',
  pillar: 'Home: pillars', traits: 'Home: personality', trait: 'Home: personality cards', stats: 'Home: numbers',
  regions: 'Home: where we\'ve been', featured: 'Home: featured trips', how: 'Home: how it works', faq: 'FAQ (answers marked TODO(owner) need your confirmation)',
  trips: 'Trips page', filter: 'Trip filters', terrain: 'Terrain names', date: 'Dates', trip: 'Trip page', lightbox: 'Photo viewer',
  join: 'Join', form: 'Membership form', privacy: 'Privacy notice (TODO(owner): review, not legal advice)', notFound: '404 page', footer: 'Footer',
};

let md = `# Copy review: Darja strings\n\n`;
md += `Generated by \`node scripts/copy-review.mjs\` from \`src/i18n/ar.json\`, the trip files and \`src/data/regions.ts\`.\n`;
md += `Every Darja string below was written by the developer and needs your review. To change one, edit the Darja\n`;
md += `in \`src/i18n/ar.json\` (or the trip file / regions file for place names), then run the script again.\n\n`;
md += `**TODO(owner): review all Darja copy.** Look for: words that don't sound like the Instagram page, anything too\n`;
md += `formal (MSA) or too "tourism agency", and wrong spellings of place names.\n\n`;

for (const [group, keys] of Object.entries(groups)) {
  md += `## ${titles[group] ?? group}\n\n| Key | Darja | English |\n|---|---|---|\n`;
  for (const k of keys) md += `| \`${k}\` | ${esc(ar[k])} | ${esc(en[k] ?? '')} |\n`;
  md += '\n';
}

md += `## Trips (src/content/trips/*.md)\n\nDates are all \`TBD\` (TODO(owner)). Summaries are kept short and generic on purpose so they stay true.\n\n`;
md += `| Trip | Title (Darja) | Title (English) | Region | Summary (Darja) | Summary (English) | Notes |\n|---|---|---|---|---|---|---|\n`;
const dir = 'src/content/trips';
for (const f of (await readdir(dir)).filter((x) => x.endsWith('.md')).sort()) {
  const raw = await readFile(join(dir, f), 'utf8');
  const front = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/)?.[1] ?? '';
  const d = parse(front);
  const notes = [];
  if (/title:[\s\S]*?ar:.*TODO/.test(front)) notes.push('check name spelling');
  if (/^region:.*TODO/m.test(front)) notes.push('provisional region');
  if (d.date === 'TBD') notes.push('date TBD');
  md += `| \`${d.slug}\` | ${esc(d.title.ar)} | ${esc(d.title.en)} | ${d.region} | ${esc(d.summary.ar)} | ${esc(d.summary.en)} | ${notes.join(', ')} |\n`;
}

const regionsSrc = await readFile('src/data/regions.ts', 'utf8');
md += `\n## Regions and place names (src/data/regions.ts)\n\n| Darja | English | Notes |\n|---|---|---|\n`;
for (const m of regionsSrc.matchAll(/\{ ar: '([^']+)', en: '([^']+)' \},?(\s*\/\/\s*(.*))?/g)) {
  md += `| ${esc(m[1])} | ${esc(m[2])} | ${m[4] ? esc(m[4]) : ''} |\n`;
}

await writeFile('docs/COPY_REVIEW.md', md);
console.log('docs/COPY_REVIEW.md written');
